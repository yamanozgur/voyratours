export function isInvalidTourTitle(title?: string, badge?: string): boolean {
  if (!title) return true;
  const lower = title.toLowerCase().trim();
  if (
    lower.startsWith('number of guests') ||
    lower.includes('number of guests') ||
    lower.includes('1-2 pax') ||
    lower.startsWith('day 1:') ||
    lower.startsWith('day 1 -') ||
    lower.startsWith('your journey begins')
  ) {
    return true;
  }
  return false;
}

export let TOURS_DATA: TourPackage[] = (() => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Filter out any corrupted or incorrectly parsed draft tours from earlier attempts
        const cleanTours = parsed.filter(
          (t: TourPackage) => !isInvalidTourTitle(t.title) && !isInvalidTourTitle(t.titleTr)
        );
        if (cleanTours.length > 0) {
          // Ensure all default tours (such as 4, 5, 8, 9 day tours) are present
          const existingIds = new Set(cleanTours.map((t: TourPackage) => t.id));
          const missingDefaults = INITIAL_TOURS_DATA.filter((t) => !existingIds.has(t.id));
          const combined = [...cleanTours, ...missingDefaults];
          
          if (combined.length !== parsed.length) {
            localStorage.setItem(STORAGE_KEY, JSON.stringify(combined));
          }
          return combined;
        }
      }
    }
  } catch (e) {
    console.error(e);
  }
  return INITIAL_TOURS_DATA;
})();

